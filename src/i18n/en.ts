const ordinalEn = (n: number) => {
  const d = n % 100;
  const suffixe = d >= 11 && d <= 13 ? 'th' : (['th', 'st', 'nd', 'rd'][n % 10] ?? 'th');
  return `${n}${suffixe}`;
};

